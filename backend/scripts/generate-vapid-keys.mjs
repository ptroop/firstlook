#!/usr/bin/env node
// Generates a VAPID keypair in the exact format the edge function expects
// (base64url uncompressed P-256 public key, 65 bytes; base64url private key,
// 32 bytes) and validates the pair by signing/verifying a JWT through the real
// module in first-look-api/push/web-push.ts.
//
// Usage (from backend/): npx.cmd tsx scripts/generate-vapid-keys.mjs
//
// Output: a gitignored .env.vapid.local at the repo root containing
// VAPID_SUBJECT, VAPID_PUBLIC_KEY, VAPID_PRIVATE_KEY and PUSH_TOKEN. Paste
// those into Supabase (Edge Function secrets + Vault) and copy the public key
// into index.html. Never commit the private key.

import { existsSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createVapidJwt, verifyVapidJwt } from '../supabase/functions/first-look-api/push/web-push.ts';

const here = dirname(fileURLToPath(import.meta.url));

function toBase64Url(bytes) {
  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

function base64UrlToBytes(value) {
  const base64 = value.replace(/-/g, '+').replace(/_/g, '/');
  const padded = base64 + '='.repeat((4 - (base64.length % 4)) % 4);
  const binary = atob(padded);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index);
  return bytes;
}

async function main() {
  const keyPair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
  const jwk = await crypto.subtle.exportKey('jwk', keyPair.privateKey);
  const publicKey = toBase64Url(new Uint8Array([4, ...base64UrlToBytes(jwk.x), ...base64UrlToBytes(jwk.y)]));
  const privateKey = toBase64Url(base64UrlToBytes(jwk.d));

  // Self-check: sign and verify a JWT with the actual production module so we
  // never hand out a keypair the edge function cannot use.
  const subject = 'mailto:first-look-alerts@example.com'; // any mailto: or https: contact; change freely, keys stay valid
  const vapid = { subject, publicKey, privateKey };
  const jwt = await createVapidJwt(vapid, 'https://fcm.googleapis.com');
  const verified = await verifyVapidJwt(jwt, { kty: 'EC', crv: 'P-256', x: jwk.x, y: jwk.y, ext: true });
  if (!verified) throw new Error('Generated VAPID keypair failed the module self-check');

  const pushToken = toBase64Url(crypto.getRandomValues(new Uint8Array(32)));

  const env = [
    '# First Look push notification keys - generated by backend/scripts/generate-vapid-keys.mjs',
    '# DO NOT COMMIT. Paste into Supabase Edge Function secrets and the public.first_look_secrets table (see backend/README.md).',
    `# Generated: ${new Date().toISOString()}`,
    `VAPID_SUBJECT=${subject}`,
    `VAPID_PUBLIC_KEY=${publicKey}`,
    `VAPID_PRIVATE_KEY=${privateKey}`,
    `PUSH_TOKEN=${pushToken}`,
    '',
  ].join('\n');

  const outputPath = resolve(here, '../../.env.vapid.local');
  // Never regenerate over an existing pair: the public key may already be
  // published in index.html and deployed, and a second keypair would make
  // every push subscription fail. Delete the file (or pass --force) to rotate.
  if (existsSync(outputPath) && !process.argv.includes('--force')) {
    throw new Error(
      `${outputPath} already exists. Refusing to overwrite: the VAPID public key may already be ` +
      `published in index.html, and a new keypair would invalidate it. Delete the file or pass --force.`,
    );
  }
  writeFileSync(outputPath, env, 'utf8');

  console.log(`Wrote ${outputPath}`);
  console.log(env);
  console.log('Public key for index.html (not secret):');
  console.log(publicKey);
  console.log('Self-check passed: JWT signed and verified with the production module.');
  console.log('Next: edit VAPID_SUBJECT in the generated file to a real mailto:/https: contact before');
  console.log('pasting values into Supabase. The subject is a JWT claim only - it can be changed later');
  console.log('without regenerating the keys.');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
